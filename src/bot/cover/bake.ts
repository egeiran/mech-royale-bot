/**
 * Offline bake of the exposure field: bun src/bot/cover/bake.ts [mapDir]
 * Writes src/bot/cover/exposure.baked.ts (gzip + base64 of encodeBaked). Re-run when the map changes.
 */
import { gzipSync } from "node:zlib"
import { writeFileSync } from "node:fs"
import { loadWorld } from "../../world/index.ts"
import { BAKE_SAMPLING, computeExposure, encodeBaked, worldFingerprint, F_STAND, F_ROOF, F_SKY } from "./exposure.ts"

const dir = process.argv[2] ?? "mechfight-kit/arena"
const world = loadWorld(dir)
const f = computeExposure(world, BAKE_SAMPLING, "baked")
const raw = encodeBaked(world, f)
const b64 = Buffer.from(gzipSync(raw, { level: 9 })).toString("base64")
let ground = 0, roof = 0, sky = 0
for (let c = 0; c < 2 * f.n; c++) {
  if (!(f.flags[c]! & F_STAND)) continue
  if (f.flags[c]! & F_ROOF) roof++
  else ground++
  if (f.flags[c]! & F_SKY) sky++
}
const lines: string[] = []
for (let i = 0; i < b64.length; i += 16000) lines.push(JSON.stringify(b64.slice(i, i + 16000)))
writeFileSync(
  new URL("./exposure.baked.ts", import.meta.url),
  `// GENERATED by \`bun src/bot/cover/bake.ts\` - do not edit. Empty string = no baked field (runtime fallback).\n// fingerprint ${worldFingerprint(world)}, sampling ${BAKE_SAMPLING.dirs} dirs x ${BAKE_SAMPLING.dists.length} dists, ${ground} ground + ${roof} roof cells, ${sky} sky-only.\nexport const BAKED =\n  ${lines.join(" +\n  ")}\n`,
)
console.log(`baked in ${f.buildMs.toFixed(0)} ms: ${ground} ground cells, ${roof} roof cells, ${sky} sky-only; raw ${raw.length} bytes, base64 ${b64.length} chars`)
